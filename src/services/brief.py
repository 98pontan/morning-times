"""Build the morning brief from the last day's articles, store it and email it."""

from __future__ import annotations

import logging
from datetime import date, datetime, timedelta
from zoneinfo import ZoneInfo

from sqlalchemy import or_, select
from sqlalchemy.orm import selectinload

from src.ai import ArticleInput, RuleSummarizer, SectionInput, Summarizer, SummarizerError
from src.db.database import Database
from src.db.models import Article, Brief, Section, Source, utcnow
from src.notifier import Notifier
from src.sections import get_plugin
from src.services.render import Renderer
from src.services.weather import WeatherService
from src.settings import Settings

log = logging.getLogger(__name__)

WINDOW = timedelta(hours=24)


class BriefService:
    def __init__(self, db: Database, summarizer: Summarizer, notifier: Notifier,
                 settings: Settings, renderer: Renderer, weather: WeatherService | None = None):
        self.db = db
        self.weather = weather
        self.summarizer = summarizer
        self.notifier = notifier
        self.settings = settings
        self.renderer = renderer

    def today(self) -> date:
        return datetime.now(ZoneInfo(self.settings.scheduler.timezone)).date()

    def generate(self, day: date | None = None, send: bool = True) -> Brief:
        day = day or self.today()
        with self.db.session() as session:
            inputs, articles, names = self._collect(session)
            generator = self.summarizer
            try:
                content = generator.write_brief(day, inputs)
            except SummarizerError:
                log.exception("Writing the brief with %s failed; falling back to headlines", generator.name)
                generator = RuleSummarizer()
                content = generator.write_brief(day, inputs)

            weather = self._weather(session)
            html = self.renderer.brief_html(day, content, articles, names, generator.name, weather)
            brief = session.scalar(select(Brief).where(Brief.date == day)) or Brief(date=day)
            brief.data = {
                "content": content.model_dump(),
                "articles": {str(k): v for k, v in articles.items()},
                "section_names": names,
                "weather": weather,
            }
            brief.html, brief.generator, brief.created_at = html, generator.name, utcnow()
            session.add(brief)

            if send:
                try:
                    self.notifier.send(content.headline, self.renderer.brief_text(day, content, articles, weather), html)
                    brief.sent_at = utcnow()
                except Exception:
                    log.exception("Sending the brief failed")
            session.flush()
            log.info("Brief for %s generated by %s (%d sections)", day, generator.name, len(content.sections))
            return brief

    def _weather(self, session) -> dict | None:
        """Forecast and SMHI warnings for weather sections; the brief is still sent if SMHI is down."""
        if self.weather is None:
            return None
        sections = session.scalars(
            select(Section).where(Section.enabled, Section.kind == "weather").order_by(Section.position)
            .options(selectinload(Section.watch_items))
        ).all()
        try:
            return self.weather.brief_snapshot(list(sections))
        except Exception:
            log.exception("Weather for the brief failed")
            return None

    def _collect(self, session) -> tuple[list[SectionInput], dict[int, dict], dict[str, str]]:
        since = utcnow() - WINDOW
        limit = self.settings.ai.max_articles_per_section
        sections = session.scalars(
            select(Section).where(Section.enabled).order_by(Section.position)
            .options(selectinload(Section.watch_items))
        ).all()
        inputs, articles, names = [], {}, {}
        for section in sections:
            plugin = get_plugin(section.kind)
            rows = session.scalars(
                select(Article).outerjoin(Source, Article.source_id == Source.id)
                .where(Article.section_id == section.id, Article.published_at >= since)
                # Skip articles from disabled sources, e.g. a region that is no longer picked.
                .where(or_(Source.id.is_(None), Source.enabled))
                .options(selectinload(Article.watch_items), selectinload(Article.source))
                .order_by(Article.published_at.desc())
                .limit(limit * 3)
            ).all()
            # Watched and important first, then newest.
            rows = sorted(rows, key=lambda a: (bool(a.watch_items), a.importance or 0, a.published_at),
                          reverse=True)[:limit]
            names[section.slug] = section.name
            inputs.append(SectionInput(
                slug=section.slug, name=section.name,
                watched=[plugin.describe_item(w) for w in section.watch_items if w.enabled],
                articles=[
                    ArticleInput(
                        id=a.id, title=a.title, summary=a.summary[:400],
                        source=a.source.name if a.source else "", published=a.published_at.isoformat(),
                        watched=[w.name for w in a.watch_items],
                    )
                    for a in rows
                ],
            ))
            for a in rows:
                articles[a.id] = {"url": a.url, "title": a.title, "source": a.source.name if a.source else ""}
        return inputs, articles, names
